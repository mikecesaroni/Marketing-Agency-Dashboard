/**
 * The whole guide as plain text.
 *
 * Written for two readers that both do badly with markup: a build step that
 * writes public/llms.txt, and a clipboard paste into a chat. Underlined
 * headings and "- " bullets survive both, where HTML and markdown tables do
 * not.
 */
export function formatAgentGuide({ baseUrl = '' } = {}) {
  const out = []
  const rule = (text, char) => text + '\n' + char.repeat(text.length)

  out.push(rule(GUIDE_TITLE.toUpperCase(), '='), '')
  for (const para of GUIDE_INTRO) out.push(para, '')

  out.push(rule('PAGES', '='), '')
  for (const route of ROUTES) {
    const paths = [route.path, ...(route.aliases || [])]
      .map((p) => (baseUrl ? baseUrl.replace(/\/$/, '') + p : p))
      .join('  or  ')
    out.push(rule(`${route.name}   ${paths}`, '-'))
    if (route.nav) out.push(`Sidebar: ${route.nav}`)
    out.push(route.purpose, '')
    out.push('What is on it:')
    for (const item of route.contains) out.push(`  - ${item}`)
    out.push('')
    out.push('What you can do:')
    for (const item of route.actions) out.push(`  - ${item}`)
    out.push('')
  }

  out.push(rule('WHERE TO FIND A PARTICULAR THING', '='), '')
  for (const l of LOOKUPS) {
    out.push(`${l.need}`)
    out.push(`  Go to: ${l.where}`)
    out.push(`  ${l.how}`, '')
  }

  out.push(rule('GETTING THINGS OUT', '='), '')
  for (const d of DOWNLOADS) {
    out.push(`${d.what}`)
    out.push(`  ${d.how}`, '')
  }

  out.push(rule('THINGS THAT WILL CATCH YOU OUT', '='), '')
  for (const g of GOTCHAS) {
    out.push(`${g.title}`)
    out.push(`  ${g.body}`, '')
  }

  return out.join('\n').replace(/\n{3,}/g, '\n\n').trimEnd() + '\n'
}
