// How to drive this CRM, written for something that has never seen it.
//
// The reader is a browsing agent: it can read a page, click, type and follow a
// link, and it has no idea what is on the other side of any of them. What it
// lacks is not intelligence, it is the thing a person picks up in their first
// week -- that money lives under Payments and not on the Dashboard, that
// publishing an ad never spends anything, that the CRM cannot delete a Meta ad
// at all. Guessing those costs a wrong click or a wrong conclusion, and both
// are worse here than not acting.
//
// So this is deliberately not a feature list. It is written as answers to the
// questions something actually asks while it works:
//
//   - where does this piece of information live
//   - how do I change it
//   - how do I get it out
//   - what will not work no matter how many times I try
//
// One spec, three consumers -- same reasoning as ghlSetupFields.js:
//
//   1. /guide, for anything that runs JavaScript, and for people
//   2. public/llms.txt, generated by scripts/build-agent-guide.mjs, for
//      anything that does not -- the same argument as privacy.html, which is a
//      static file because Meta's reviewer does not reliably run JS
//   3. the Copy button on /guide, for pasting into a chat
//
// ROUTES are checked against the router and the nav by
// scripts/check-agent-guide.mjs. A page added, moved or renamed without this
// file being updated fails that check, which is the only reason to trust
// anything written below: a stale guide is worse than none, because it is
// followed confidently.

