// The weekly client report: the week maths, who gets one, the numbers, the
// plain-English sentences, and the email and web copy. Plain JavaScript in a
// .ts file so the Edge Function (Deno) and the app (Vite) load the very same
// code; src/lib/weeklyReport.js re-exports it from supabase/functions/weekly-report/weekly.ts.
//
// WHAT THE REPORT IS FOR. A home-services owner wants to know three things
// on a Monday morning: what did I spend, what did I get, and is it working.
// So the report is five numbers, two or three sentences on what they mean,
// a short glossary, and one argument made every week: the number that
// decides whether the ads are worth it is the return on the leads, not the
// cost per lead, and the only person who knows that number is the owner.
// The web copy asks for it in one line.
//
// TONE. Short sentences, everyday words, no hype. Every sentence is a fixed
// template with the week's numbers dropped in; nothing here is generated by
// a model, so it reads the same way every week and never over-promises.

export const LIVE_STATUSES = ['ACTIVE', 'WITH_ISSUES']

const pad = (n) => String(n).padStart(2, '0')
export const isoDay = (d) => `${d.getFullYear()}-${pad(d.getMonth() + 1)}-${pad(d.getDate())}`
const fromIso = (s) => {
  const [y, m, d] = String(s).split('-').map(Number)
  return new Date(y, m - 1, d)
}
const addDays = (s, n) => {
  const d = fromIso(s)
  d.setDate(d.getDate() + n)
  return isoDay(d)
}

const MONTHS = ['Jan', 'Feb', 'Mar', 'Apr', 'May', 'Jun', 'Jul', 'Aug', 'Sep', 'Oct', 'Nov', 'Dec']
const shortDate = (s) => {
  const d = fromIso(s)
  return `${MONTHS[d.getMonth()]} ${d.getDate()}`
}

/**
 * The Monday-to-Sunday week that ended before `today`. On a Monday that is
 * last week; on any other day it is the most recent complete week.
 */
export function reportWeek(today = new Date()) {
  const t = typeof today === 'string' ? fromIso(today) : new Date(today)
  // Days back to the most recent Sunday strictly before today.
  const dow = t.getDay() // 0 = Sunday
  const back = dow === 0 ? 7 : dow
  const sunday = new Date(t.getFullYear(), t.getMonth(), t.getDate() - back)
  const monday = new Date(sunday.getFullYear(), sunday.getMonth(), sunday.getDate() - 6)
  const from = isoDay(monday)
  const to = isoDay(sunday)
  return { from, to, key: from, label: weekLabel(from, to) }
}

/** A week from its Monday, for re-running a specific one. */
export function weekFrom(mondayIso) {
  const from = String(mondayIso)
  const to = addDays(from, 6)
  return { from, to, key: from, label: weekLabel(from, to) }
}

export function previousWeek(week) {
  return weekFrom(addDays(week.from, -7))
}

/** "Sep 29 to Oct 5" with the year when the week crosses into a new one. */
export function weekLabel(from, to) {
  const a = fromIso(from)
  const b = fromIso(to)
  const year = a.getFullYear() !== b.getFullYear() ? `, ${b.getFullYear()}` : ''
  return `${shortDate(from)} to ${shortDate(to)}${year}`
}

// Deliberately strict: a malformed address does not bounce cleanly.
export function validEmail(value) {
  const v = String(value || '').trim()
  return /^[^\s@]+@[^\s@]+\.[A-Za-z]{2,}$/.test(v)
}

const num = (v) => Number(v || 0) || 0
const r2 = (n) => Math.round(n * 100) / 100

/** Meta rows (ad_daily) and Google rows (google_campaign_daily) summed to one shape. */
export function sumMeta(rows = []) {
  const t = { spend: 0, leads: 0, impressions: 0, clicks: 0 }
  for (const r of rows) {
    t.spend += num(r.spend)
    t.leads += num(r.leads)
    t.impressions += num(r.impressions)
    t.clicks += num(r.clicks)
  }
  return t
}
export function sumGoogle(rows = []) {
  const t = { spend: 0, leads: 0, impressions: 0, clicks: 0 }
  for (const r of rows) {
    t.spend += num(r.cost)
    t.leads += num(r.conversions)
    t.impressions += num(r.impressions)
    t.clicks += num(r.clicks)
  }
  return t
}

/** Spend, leads, impressions, clicks, and the two rates. */
export function metrics(t) {
  const spend = r2(t.spend)
  const leads = Math.round(num(t.leads) * 10) / 10
  const impressions = Math.round(num(t.impressions))
  const clicks = Math.round(num(t.clicks))
  return {
    spend,
    leads,
    impressions,
    clicks,
    cpl: leads > 0 ? r2(spend / leads) : 0,
    ctr: impressions > 0 ? r2((clicks / impressions) * 100) : 0,
  }
}

const addTotals = (a, b) => ({
  spend: a.spend + b.spend,
  leads: a.leads + b.leads,
  impressions: a.impressions + b.impressions,
  clicks: a.clicks + b.clicks,
})

/**
 * Who gets a report. Every refusal carries a reason for the send log.
 * The address is the client's report email when set, else the contact
 * email on the intake form.
 */
export function eligibility({ client, intake, metaRows = [], googleRows = [] }) {
  if (!client) return { ok: false, reason: 'no client' }
  if (client.archived) return { ok: false, reason: 'archived' }
  if (client.is_internal) return { ok: false, reason: 'internal business, not a client' }
  if (client.weekly_report_enabled === false) return { ok: false, reason: 'weekly report switched off for this client' }
  const spend = sumMeta(metaRows).spend + sumGoogle(googleRows).spend
  if (spend <= 0) return { ok: false, reason: 'no ad spend last week' }
  const email = String(client.report_email || intake?.contact_email || '').trim()
  if (!email) return { ok: false, reason: 'no email on file (set one on the client, or on the onboarding form)' }
  if (!validEmail(email)) return { ok: false, reason: `email is not valid: ${email}` }
  return { ok: true, email }
}

/** Percent change, null when there is nothing to compare against. */
export function pctChange(now, before) {
  if (!before) return null
  return Math.round(((now - before) / before) * 100)
}

const stripWc = (name) => {
  // "WC_Summer | 2026-10-08 | AC died? Same-day" shows as "AC died? Same-day".
  const s = String(name || '').replace(/^wc_/i, '')
  const parts = s.split('|').map((x) => x.trim()).filter(Boolean)
  return parts.length > 1 ? parts[parts.length - 1] : s
}

/**
 * Everything the email and the web copy need, worked out once.
 *   lastAnswer: { jobs_booked, revenue, week } from the previous report, if the
 *   client answered it.
 */
export function buildWeeklyModel({ client, intake, week, metaRows = [], googleRows = [], prevMetaRows = [], prevGoogleRows = [], lastAnswer = null }) {
  const meta = sumMeta(metaRows)
  const google = sumGoogle(googleRows)
  const prevMeta = sumMeta(prevMetaRows)
  const prevGoogle = sumGoogle(prevGoogleRows)
  const totals = metrics(addTotals(meta, google))
  const previous = metrics(addTotals(prevMeta, prevGoogle))
  const hadPrevious = previous.spend > 0

  // The ad that brought the most leads, by name, across both channels.
  const byAd = new Map()
  for (const r of metaRows) {
    const key = r.ad_id || r.ad_name
    const a = byAd.get(key) || { name: stripWc(r.ad_name) || 'Untitled ad', leads: 0, spend: 0, channel: 'Meta' }
    a.leads += num(r.leads)
    a.spend += num(r.spend)
    byAd.set(key, a)
  }
  for (const r of googleRows) {
    const key = `g:${r.campaign_id || r.campaign_name}`
    const a = byAd.get(key) || { name: stripWc(r.campaign_name) || 'Google campaign', leads: 0, spend: 0, channel: 'Google' }
    a.leads += num(r.conversions)
    a.spend += num(r.cost)
    byAd.set(key, a)
  }
  const topAd = [...byAd.values()].filter((a) => a.leads > 0).sort((x, y) => y.leads - x.leads || x.spend - y.spend)[0] || null

  const avgJob = num(intake?.average_job_value) > 0 ? num(intake.average_job_value) : null

  const model = {
    client: { name: client.name },
    week,
    channels: {
      meta: meta.spend > 0 ? metrics(meta) : null,
      google: google.spend > 0 ? metrics(google) : null,
    },
    totals,
    previous: hadPrevious ? previous : null,
    deltas: hadPrevious
      ? {
          spend: pctChange(totals.spend, previous.spend),
          leads: pctChange(totals.leads, previous.leads),
          cpl: pctChange(totals.cpl, previous.cpl),
          ctr: pctChange(totals.ctr, previous.ctr),
          impressions: pctChange(totals.impressions, previous.impressions),
        }
      : null,
    topAd: topAd ? { name: topAd.name, leads: Math.round(topAd.leads * 10) / 10, spend: r2(topAd.spend), channel: topAd.channel } : null,
    avgJob,
    lastAnswer: lastAnswer && (num(lastAnswer.jobs_booked) > 0 || num(lastAnswer.revenue) > 0) ? { jobs: num(lastAnswer.jobs_booked), revenue: num(lastAnswer.revenue), week: lastAnswer.week || '', spend: num(lastAnswer.spend) } : null,
  }
  model.summary = summarySentences(model)
  model.returnNote = returnNote(model)
  return model
}

export const money = (n) => {
  const v = Number(n || 0)
  const whole = Math.abs(v) >= 100 || Number.isInteger(v)
  return `$${v.toLocaleString('en-US', { minimumFractionDigits: whole ? 0 : 2, maximumFractionDigits: whole ? 0 : 2 })}`
}
const plural = (n, one, many) => (Number(n) === 1 ? one : many)
const leadsWord = (n) => `${n} ${plural(n, 'lead', 'leads')}`

/**
 * Two or three sentences on what the week's numbers mean. Fixed templates,
 * the week's numbers dropped in. Each case is one plain thought.
 */
export function summarySentences(model) {
  const { totals, previous, deltas } = model
  const out = []

  if (totals.leads === 0) {
    out.push(`No leads came in last week on ${money(totals.spend)} of ad spend.`)
    if (totals.impressions > 0 && totals.ctr < 1) {
      out.push('The ads were shown but few people tapped, which usually means the same people have seen them too many times. A fresh ad is the fix, and that is what we work on first.')
    } else {
      out.push('A week with no leads is one we look into straight away, so expect to hear from us before the next report.')
    }
    return out
  }

  if (!previous) {
    out.push(`You got ${leadsWord(totals.leads)} last week from ${money(totals.spend)} in ads, which works out to ${money(totals.cpl)} per lead.`)
    out.push('This is your first full week, so there is nothing to compare it with yet. Next week you will see whether each number went up or down.')
  } else {
    const dl = totals.leads - previous.leads
    const leadsBit =
      dl > 0 ? `up from ${previous.leads} the week before` : dl < 0 ? `down from ${previous.leads} the week before` : `the same as the week before`
    out.push(`You got ${leadsWord(totals.leads)} last week from ${money(totals.spend)} in ads, ${leadsBit}.`)
    if (totals.cpl > 0 && previous.cpl > 0) {
      const dc = totals.cpl - previous.cpl
      if (Math.abs(dc) < 1) out.push(`Each lead cost about ${money(totals.cpl)}, about the same as the week before.`)
      else if (dc < 0) out.push(`Each lead cost ${money(totals.cpl)}, ${money(Math.abs(dc))} less than the week before.`)
      else out.push(`Each lead cost ${money(totals.cpl)}, ${money(dc)} more than the week before. Cost per lead moves around week to week; the trend over a month is what we watch.`)
    } else if (totals.cpl > 0) {
      out.push(`Each lead cost ${money(totals.cpl)}.`)
    }
  }

  if (totals.impressions > 0) {
    if (totals.ctr >= 2) out.push(`${totals.ctr}% of the people who saw the ad tapped it, which is a strong sign the ad is catching attention.`)
    else if (totals.ctr < 0.8) out.push(`${totals.ctr}% of the people who saw the ad tapped it, which is on the low side. That usually means the ad needs refreshing, and new creative is part of every month.`)
  }

  return out.slice(0, 3)
}

/**
 * The argument the report makes every week: judge the ads on what the leads
 * turned into, not on what they cost. Worked with the client's own numbers
 * when we have them.
 */
export function returnNote(model) {
  const { totals, avgJob, lastAnswer } = model
  const lines = []
  if (lastAnswer && lastAnswer.revenue > 0 && lastAnswer.spend > 0) {
    const back = Math.round((lastAnswer.revenue / lastAnswer.spend) * 100) / 100
    lines.push(
      `Last week you told us the leads became ${lastAnswer.jobs} ${plural(lastAnswer.jobs, 'job', 'jobs')} worth ${money(lastAnswer.revenue)}. Against ${money(lastAnswer.spend)} in ads, that is ${money(back)} back for every $1 spent. That is the number that matters, and it is why we ask every week.`
    )
  } else if (lastAnswer && lastAnswer.jobs > 0) {
    lines.push(`Last week you told us the leads became ${lastAnswer.jobs} ${plural(lastAnswer.jobs, 'job', 'jobs')}. Add the dollar amount next time and we will show your return on the ads.`)
  }
  if (totals.leads > 0) {
    const jobs = Math.max(1, Math.round(totals.leads / 5))
    if (avgJob) {
      lines.push(
        `For this week: if ${jobs} of the ${totals.leads} leads ${plural(jobs, 'becomes', 'become')} a job at your usual ${money(avgJob)}, that is ${money(jobs * avgJob)} of work from ${money(totals.spend)} in ads.`
      )
    } else {
      lines.push(
        `For this week: if ${jobs} of the ${totals.leads} leads ${plural(jobs, 'becomes', 'become')} a job, what is that worth to you? Compare it with the ${money(totals.spend)} the ads cost. That comparison, not cost per lead, is how to judge the ads.`
      )
    }
  }
  return lines
}

