const INK = '#0F172A'
const MUTED = '#64748B'
const LINE = '#E2E8F0'
const SOFT = '#F8FAFC'
const BRAND = '#EA580C'

function esc(value) {
  return String(value ?? '')
    .replace(/&/g, '&amp;')
    .replace(/</g, '&lt;')
    .replace(/>/g, '&gt;')
    .replace(/"/g, '&quot;')
    .replace(/'/g, '&#39;')
}

// Green when the move is good, red when it is bad, grey when it is neither
// (spend going up is just a fact, not a win or a loss).
function deltaHtml(value, { lowerIsBetter = false, neutral = false } = {}) {
  if (value == null || !Number.isFinite(value)) return ''
  const flat = Math.abs(value) < 1
  const up = value > 0
  const good = flat || neutral ? null : lowerIsBetter ? !up : up
  const colour = good === null ? MUTED : good ? '#15803D' : '#B91C1C'
  const arrow = flat ? '' : up ? '&#9650;' : '&#9660;'
  const words = flat ? 'same as last week' : `${arrow} ${Math.abs(value)}% vs last week`
  return `<div style="font-size:11px;color:${colour};padding-top:3px;">${words}</div>`
}

function tile(label, value, delta) {
  return (
    `<td width="20%" valign="top" style="padding:12px 8px;border:1px solid ${LINE};border-radius:8px;background:#fff;">` +
    `<div style="font-size:11px;color:${MUTED};text-transform:uppercase;letter-spacing:.3px;">${label}</div>` +
    `<div style="font-size:21px;font-weight:700;color:${INK};padding-top:3px;white-space:nowrap;">${value}</div>` +
    `${delta}</td>`
  )
}

const fmtInt = (n) => Number(n || 0).toLocaleString('en-US')
const fmtLeads = (n) => (Number.isInteger(Number(n)) ? String(n) : Number(n).toFixed(1))

export function renderWeeklySubject(model) {
  const { totals, week } = model
  if (totals.leads === 0) return `Your ads last week (${week.label}): ${money(totals.spend)} spent, no leads yet`
  return `Your ads last week (${week.label}): ${leadsWord(fmtLeads(totals.leads))} from ${money(totals.spend)}`
}

